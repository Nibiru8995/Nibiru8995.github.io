/* Есть ли между картами парная синергия (в любую сторону) */
function pairApplies(cardA, cardB, pair) {
  return (cardA.id === pair.a && cardB.id === pair.b) || (cardA.id === pair.b && cardB.id === pair.a);
}
/* Звери без пар: связность между ними всегда false —
   hintClass и тултипы честно показывают «рацион вместо синергий» */
function pairsForCard(card) {
  return SYNERGY_PAIRS.filter(p => p.a === card.id || p.b === card.id);
}
/* Быстрый поиск пары по двум картам (O(1) вместо перебора) */
const PAIR_LOOKUP = {};
SYNERGY_PAIRS.forEach((p, i) => { PAIR_LOOKUP[p.a + '|' + p.b] = i; PAIR_LOOKUP[p.b + '|' + p.a] = i; });
function findPair(cardA, cardB) {
  const i = PAIR_LOOKUP[cardA.id + '|' + cardB.id];
  return i === undefined ? null : SYNERGY_PAIRS[i];
}
