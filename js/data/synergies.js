const UNDEAD_LINK_BY_RARITY = { 3: 0.6, 4: 1.1, 5: 1.6 };
const UNDEAD_LINK_SUB_MULT = { skeleton: 1.25, ghost: 1, vampire: 1 };
const UNDEAD_SUB_RULE = {
  skeleton: 'Скелеты: связаны с соседями-скелетами (+25% к звеньям), здания мёртвых усиливают их в 1.5 раза',
  ghost: 'Призраки: связаны с соседями-призраками, в том числе через клетку (пунктир, половина силы)',
  vampire: 'Вампиры: связаны с соседями-вампирами; раны соседей питают Кровоток'
};
const UNDEAD_SUB_TITLE = { skeleton: 'Скелеты', ghost: 'Призраки', vampire: 'Вампиры' };
{
  const ids = Object.keys(CARDS).filter(id => CARDS[id].faction === 'undead' && !CARDS[id].isBuilding);
  for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) {
    const A = CARDS[ids[i]], B = CARDS[ids[j]];
    if (!A.subrace || A.subrace !== B.subrace) continue;
    if (A.id === 'u10' || B.id === 'u10' || A.id === 'u11' || B.id === 'u11') continue; /* у них свои звенья ниже */
    if (A.id === 'u26' || B.id === 'u26') continue;
    const top = Math.max(+A.rarity, +B.rarity);
    const v = Math.round((UNDEAD_LINK_BY_RARITY[top] || 1) * (UNDEAD_LINK_SUB_MULT[A.subrace] || 1) * 100) / 100;
    addPair(A.id, B.id, 'flat', v, UNDEAD_SUB_TITLE[A.subrace] + ': связь с соседом → +' + v + '/с');
    SYNERGY_PAIRS[SYNERGY_PAIRS.length - 1].generic = true;
  }
}
