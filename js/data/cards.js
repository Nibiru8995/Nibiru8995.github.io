const RARITY_HP = { 1: 30, 3: 45, 4: 65, 5: 90 };
function cardHp(rarity) { return RARITY_HP[rarity] || 30; }
function fighterHp(rarity) { return { 1: 100, 3: 300, 4: 800, 5: 2000 }[rarity] || 100; }
function fighterDmg(rarity) { return { 1: 10, 3: 35, 4: 120, 5: 350 }[rarity] || 10; }

function rarityColor(r) { return r === 1 ? '#6a5a4a' : r === 3 ? '#7080a0' : r === 4 ? '#a070b0' : '#d4b050'; }
function rarityBg(r) { return r === 1 ? '#3a2a20' : r === 3 ? '#202a40' : r === 4 ? '#3a2040' : '#4a3010'; }
