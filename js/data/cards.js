/* Редкости бойцов: HP и урон для Арены ('B' Здание = бывшая ★1) */
const RARITY_HP = { B: 30, 1: 30, 3: 45, 4: 65, 5: 90 };
function cardHp(rarity) { return RARITY_HP[rarityRank(rarity)] || 30; }
function fighterHp(rarity) { return { B: 100, 1: 100, 3: 300, 4: 800, 5: 2000 }[rarityRank(rarity)] || 100; }
function fighterDmg(rarity) { return { B: 10, 1: 10, 3: 35, 4: 120, 5: 350 }[rarityRank(rarity)] || 10; }

function rarityColor(r) { return r === 'B' ? '#9a8a6a' : r === 1 ? '#6a5a4a' : r === 3 ? '#7080a0' : r === 4 ? '#a070b0' : '#d4b050'; }
function rarityBg(r) { return r === 'B' ? '#2e2618' : r === 1 ? '#3a2a20' : r === 3 ? '#202a40' : r === 4 ? '#3a2040' : '#4a3010'; }
